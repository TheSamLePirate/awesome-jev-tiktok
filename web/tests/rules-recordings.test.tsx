    const connect = spyOn(api, "connect").mockResolvedValue({ ok: true, sessionId: "s" } as any);
    const del = spyOn(api, "deleteRecording").mockResolvedValue({ ok: true } as any);
    const inactive = render(<Recordings live={false} active={false} />);
    expect(inactive.container.textContent).toContain("Loading…"); expect(list).not.toHaveBeenCalled();
    inactive.unmount();
    const { container, rerender } = render(<><Recordings live={false} currentBase="rec-1" replayOf="rec-2" active /><DialogHost /></>);
    await waitFor(() => expect(container.querySelectorAll(".rec").length).toBe(2));
