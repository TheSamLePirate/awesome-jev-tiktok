import { describe, expect, spyOn, test } from "bun:test";
import { act, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { RulesPanel } from "../components/RulesPanel";
import { Recordings } from "../components/Recordings";
import { DialogHost } from "../components/Dialog";
import { api } from "../lib/api";
import { getState } from "../lib/store";
import { choiceQ, localQ, messageQ, qset, question, recording, rule, scoreQ, T0 } from "./fixtures";

describe("RulesPanel", () => {
  test("compose a jev rule and a keyword rule, examples, sources, errors", async () => {
    const add = spyOn(api, "addRule").mockResolvedValue({ ok: true, rule: {} } as any);
    const { container } = render(<><RulesPanel rules={[]} questions={null} compiling={false} /><DialogHost /></>);
    const ta = screen.getByLabelText("new rule") as HTMLTextAreaElement;
    expect((screen.getByText(/Add rule/).closest("button") as HTMLButtonElement).disabled).toBe(true);
    fireEvent.click(screen.getByText("💬 pricing questions"));
    expect(ta.value).toContain("price"); expect(container.querySelectorAll(".src-btn.on").length).toBe(1);
    fireEvent.click(screen.getByText("🎙 host promises"));
    const dlg = container.querySelector("dialog")!;
    await waitFor(() => expect(dlg.open).toBe(true));
    fireEvent.click(screen.getByText("Cancel"));
    expect(ta.value).toContain("price");
    fireEvent.click(screen.getByText("🎙 host promises"));
    await waitFor(() => expect(dlg.open).toBe(true));
    fireEvent.click(screen.getByText("Replace"));
    await waitFor(() => expect(ta.value).toContain("promises"));
    fireEvent.click(screen.getByText("🎙 host promises"));
    fireEvent.click(screen.getByText("💬 chat")); expect(container.querySelectorAll(".src-btn.on").length).toBe(2);
    fireEvent.click(screen.getByText("💬 chat")); fireEvent.click(screen.getByText("🎙 audio")); expect(container.querySelectorAll(".src-btn.src-transcript.on").length).toBe(1);
    fireEvent.click(screen.getByText("✦ all")); expect(container.querySelectorAll(".src-btn.on").length).toBe(4);
    fireEvent.keyDown(ta, { key: "Enter", metaKey: true });
    await waitFor(() => expect(add).toHaveBeenCalled());
    expect(add.mock.calls[0][0]).toMatchObject({ sources: ["transcript", "video", "chat"] });
    await waitFor(() => expect(ta.value).toBe(""));
    fireEvent.keyDown(ta, { key: "Enter", metaKey: true });
    expect(add).toHaveBeenCalledTimes(1);
    fireEvent.click(screen.getByText("⌘ keyword / regex"));
    fireEvent.click(screen.getByText("🔗 links"));
    const pat = screen.getByLabelText("pattern") as HTMLInputElement;
    expect(pat.value).toContain("https");
    fireEvent.change(pat, { target: { value: "(" } });
    expect(container.querySelector(".error.small")).not.toBeNull(); expect((screen.getByText(/Add rule/).closest("button") as HTMLButtonElement).disabled).toBe(true);
    fireEvent.change(pat, { target: { value: "\\bprix\\b" } });
    add.mockRejectedValue(new Error("server said no"));
    fireEvent.click(screen.getByText(/Add rule/).closest("button")!);
    await waitFor(() => expect(container.querySelector(".error:not(.small)")?.textContent).toBe("server said no"));
    expect(add.mock.calls[1][0]).toMatchObject({ kind: "keyword", pattern: "\\bprix\\b", flags: "i", sources: ["chat"] });
    fireEvent.change(pat, { target: { value: "" } });
    expect((screen.getByText(/Add rule/).closest("button") as HTMLButtonElement).disabled).toBe(true);
    fireEvent.click(screen.getByText("✦ jev rule"));
    expect(screen.queryByLabelText("pattern")).toBeNull();
    fireEvent.change(ta, { target: { value: "typed by hand" } });
    expect((screen.getByText(/Add rule/).closest("button") as HTMLButtonElement).disabled).toBe(false);
    add.mockRestore();
  });
  test("rule items: question details, pause, remove with undo, compiling", async () => {
    const pause = spyOn(api, "pauseRule").mockResolvedValue({ ok: true } as any);
    const remove = spyOn(api, "removeRule").mockResolvedValue({ ok: true, undoMs: 60_000 } as any);
    const restore = spyOn(api, "restoreRule").mockResolvedValue({ ok: true } as any);
    const rules = [rule(), rule({ id: "r2", text: "mood", sources: ["chat", "transcript"] }), rule({ id: "r3", text: "links", kind: "keyword", paused: true, sources: ["chat"] }), rule({ id: "r4", text: "compiling", sources: ["chat"] })];
    const qs = qset([question(), choiceQ({ ruleId: "r2" }), scoreQ({ ruleId: "r2" }), messageQ({ ruleId: "r2", alert: undefined }), localQ(), question({ id: "q9", ruleId: "r2", alert: {} , question: { type: "noul", instructions: { obj: 1 } } })]);
    const { container } = render(<RulesPanel rules={rules} questions={qs} compiling />);
    expect(container.querySelectorAll(".rule").length).toBe(4); expect(container.textContent).toContain("GLM is writing the questions…"); expect(container.querySelectorAll(".rule.paused").length).toBe(1);
    const heads = container.querySelectorAll(".qd-head");
    expect(heads.length).toBe(6);
    for (const h of heads) fireEvent.click(h);
    expect(container.textContent).toContain("fires when yes ≥ 70%"); expect(container.textContent).toContain("answer is tense"); expect(container.textContent).toContain("level ≥ 2"); expect(container.textContent).toContain("fires when —");
    expect(container.querySelectorAll(".qd-list").length).toBe(3); expect(container.textContent).toContain('{"obj":1}');
    fireEvent.click(heads[0]); expect(container.querySelectorAll(".qd.open").length).toBe(5);
    fireEvent.click(container.querySelector('[aria-label="resume rule"]')!);
    await waitFor(() => expect(pause).toHaveBeenCalledWith("r3", false));
    fireEvent.click(container.querySelector('[aria-label="pause rule"]')!);
    await waitFor(() => expect(pause).toHaveBeenCalledWith("r1", true));
    fireEvent.click(container.querySelector('[aria-label="remove rule"]')!);
    await waitFor(() => expect(remove).toHaveBeenCalledWith("r1"));
    await waitFor(() => expect(getState().toasts.some((t) => t.title === "Rule removed")).toBe(true));
    act(() => getState().toasts.find((t) => t.title === "Rule removed")!.action!.run());
    expect(restore).toHaveBeenCalledWith("r1");
    pause.mockRejectedValue(new Error("x")); remove.mockRejectedValue(new Error("x")); restore.mockRejectedValue(new Error("x"));
    fireEvent.click(container.querySelectorAll('[aria-label="pause rule"]')[1]);
    fireEvent.click(container.querySelectorAll('[aria-label="remove rule"]')[2]);
    await waitFor(() => expect(remove).toHaveBeenCalledTimes(2));
    act(() => getState().toasts.find((t) => t.title === "Rule removed")!.action!.run());
    await new Promise((r) => setTimeout(r, 20));
    expect(restore).toHaveBeenCalledTimes(2);
    render(<RulesPanel rules={[rule({ id: "r9", text: "no questions yet" })]} questions={null} compiling={false} />);
    expect(screen.getByText("no questions")).toBeTruthy();
    pause.mockRestore(); remove.mockRestore(); restore.mockRestore();
  });
});

describe("Recordings", () => {
  test("list, search, select with peek, replay, simulate, delete, refresh, inactive", async () => {
    const list = spyOn(api, "recordings").mockResolvedValue([recording(), recording({ id: "rec-2", username: "other", title: undefined, durationSec: undefined, videos: [], sizeBytes: 500 })]);
    const peek = spyOn(api, "peekRecording").mockResolvedValue({ chat: [{ ts: T0 + 100, handle: "alice", nickname: "Alice", text: "hi" }], transcript: [{ ts: T0 + 50, text: "welcome" }], captions: [{ ts: T0, text: "a desk" }], timeline: [{ t: 0, chat: 3, transcript: 1 }, { t: 2, chat: 0, transcript: 2 }] });
    const connect = spyOn(api, "connect").mockResolvedValue({ ok: true, sessionId: "s" } as any);
    const del = spyOn(api, "deleteRecording").mockResolvedValue({ ok: true } as any);
    const inactive = render(<Recordings live={false} active={false} />);
    expect(inactive.container.textContent).toContain("Loading…"); expect(list).not.toHaveBeenCalled();
    inactive.unmount();
    const { container, rerender } = render(<><Recordings live={false} currentBase="rec-1" replayOf="rec-2" active /><DialogHost /></>);
    await waitFor(() => expect(container.querySelectorAll(".rec").length).toBe(2));
    expect(container.textContent).toContain("2 sessions · 1 videos"); expect(container.textContent).toContain("recording now"); expect(container.textContent).toContain("replaying");
    fireEvent.change(screen.getByLabelText("search recordings"), { target: { value: "OTHER" } });
    expect(container.querySelectorAll(".rec").length).toBe(1);
    fireEvent.change(screen.getByLabelText("search recordings"), { target: { value: "" } });
    fireEvent.click(container.querySelector(".rec-head")!);
    await waitFor(() => expect(container.querySelector(".rec-timeline")).not.toBeNull());
    expect(peek).toHaveBeenCalledWith("rec-1"); expect(container.querySelectorAll(".rec-bar").length).toBe(13); expect(container.textContent).toContain("welcome"); expect(container.textContent).toContain("a desk");
    expect((screen.getByText("▶ Replay") as HTMLButtonElement).disabled).toBe(false);
    fireEvent.click(screen.getByText("▶ Replay"));
    await waitFor(() => expect(connect).toHaveBeenCalledWith("replay", "rec-1", { simulate: false }));
    fireEvent.click(screen.getByText("⚙ Simulate live"));
    await waitFor(() => expect(connect).toHaveBeenCalledWith("replay", "rec-1", { simulate: true }));
    expect((container.querySelector(".rec-actions .danger") as HTMLButtonElement).disabled).toBe(true);
    fireEvent.click(container.querySelector(".rec-head")!);
    expect(container.querySelector(".rec-detail")).toBeNull();
    peek.mockRejectedValue(new Error("gone"));
    fireEvent.click(container.querySelectorAll(".rec-head")[1]);
    await waitFor(() => expect(peek).toHaveBeenCalledWith("rec-2"));
    expect(container.querySelector(".skeleton")).not.toBeNull();
    rerender(<><Recordings live={false} active /><DialogHost /></>);
    await waitFor(() => expect(container.querySelectorAll(".rec-actions").length).toBe(1));
    fireEvent.click(screen.getByText("🗑 delete"));
    const dlg = container.querySelector("dialog")!;
    await waitFor(() => expect(dlg.open).toBe(true));
    fireEvent.click(screen.getByText("Cancel"));
    expect(del).not.toHaveBeenCalled();
    fireEvent.click(screen.getByText("🗑 delete"));
    await waitFor(() => expect(dlg.open).toBe(true));
    fireEvent.click(screen.getByText("Delete"));
    await waitFor(() => expect(del).toHaveBeenCalledWith("rec-2"));
    await waitFor(() => expect(getState().toasts.some((t) => t.title === "Recording deleted")).toBe(true));
    fireEvent.click(screen.getByLabelText("refresh"));
    await waitFor(() => expect(list.mock.calls.length).toBeGreaterThanOrEqual(3));
    // Live: replay disabled; delete of a session with videos asks with the size; errors are swallowed.
    rerender(<><Recordings live active /><DialogHost /></>);
    fireEvent.click(container.querySelectorAll(".rec-head")[0]);
    await waitFor(() => expect(container.querySelectorAll(".rec-actions").length).toBe(1));
    expect((screen.getByText("▶ Replay") as HTMLButtonElement).disabled).toBe(true);
    del.mockRejectedValue(new Error("x"));
    fireEvent.click(screen.getByText("🗑 delete"));
    await waitFor(() => expect(dlg.textContent).toContain("1 video file"));
    fireEvent.click(screen.getByText("Delete"));
    await waitFor(() => expect(del).toHaveBeenCalledTimes(2));
    connect.mockRejectedValue(new Error("x"));
    rerender(<><Recordings live={false} active /><DialogHost /></>);
    fireEvent.click(screen.getByText("▶ Replay"));
    await waitFor(() => expect(connect).toHaveBeenCalledTimes(3));
    list.mockRejectedValue(new Error("down"));
    fireEvent.click(screen.getByLabelText("refresh"));
    list.mockResolvedValue([]);
    rerender(<><Recordings live={false} active={false} /><DialogHost /></>);
    rerender(<><Recordings live={false} active /><DialogHost /></>);
    await waitFor(() => expect(container.textContent).toContain("No recordings yet"));
    list.mockRestore(); peek.mockRestore(); connect.mockRestore(); del.mockRestore();
  });
});
