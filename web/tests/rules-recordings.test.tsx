    fireEvent.change(screen.getByLabelText("search recordings"), { target: { value: "" } });
    fireEvent.click(container.querySelector(".rec-head")!);
    await waitFor(() => expect(container.querySelector(".rec-timeline")).not.toBeNull());
    expect(peek).toHaveBeenCalledWith("rec-1"); expect(container.querySelectorAll(".rec-bar").length).toBe(13); expect(container.textContent).toContain("welcome"); expect(container.textContent).toContain("a desk");
