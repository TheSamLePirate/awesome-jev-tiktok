import { describe, expect, mock, spyOn, test } from "bun:test";
import { act, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { ChatFeed } from "../components/ChatFeed";
import { Flagged, removeWithUndo } from "../components/Flagged";
import { DialogHost } from "../components/Dialog";
import { api } from "../lib/api";
import { getState } from "../lib/store";
import { chat, highlight, localQ, messageDecision, messageQ, question, roomHl, sceneHl, transcriptHl, T0 } from "./fixtures";

const scrollBox = (el: Element, top: number) => { Object.defineProperty(el, "scrollHeight", { value: 1000, configurable: true }); Object.defineProperty(el, "clientHeight", { value: 100, configurable: true }); el.scrollTop = top; fireEvent.scroll(el); };

describe("ChatFeed", () => {
  test("groups, flags, filters, search, user card with mute, focus and unread jump", async () => {
    const now = Date.now();
    const msgs = [chat({ id: "c1", ts: now - 5000, text: "hello?" }), chat({ id: "c2", ts: now - 4000, text: "http://spam.example" }), chat({ id: "c3", ts: now - 3000, userId: "u2", handle: "bob", nickname: "", text: "yo", isFollower: true, avatar: undefined }), chat({ id: "c4", ts: now - 60_000, text: "old and unjudged" }), chat({ id: "c5", ts: now - 1000, userId: "u2", handle: "bob", nickname: "", text: "again" })];
    const decisions = { c1: messageDecision({ messageId: "c1", answers: { m1: { type: "noul", noul: 0.9 }, k1: { type: "noul", noul: 0 } }, fired: ["m1"] }), c2: messageDecision({ messageId: "c2", answers: { k1: { type: "noul", noul: 1 } }, fired: ["k1"], skipped: ["m1"] }), c3: messageDecision({ messageId: "c3", answers: { m1: { type: "noul", noul: 0.1 } }, fired: [] }) };
    const onOpenFlag = mock(() => {});
    const qs = [messageQ(), localQ(), messageQ({ id: "m2", label: "Ask", question: { type: "choice", instructions: "asks?", criteria: {} } }), messageQ({ id: "m3", label: "Level", question: { type: "score", instructions: "level", criteria: [] } })];
    const dec2 = { ...decisions, c3: messageDecision({ messageId: "c3", answers: { m1: { type: "noul", noul: 0.1 }, m2: { type: "choice", choice: "big_q", probabilities: {}, confidence: 0.7 }, m3: { type: "score", score: 1.25, legend: {}, probabilities: {}, confidence: 1 } }, fired: [] }) };
    const { container, rerender } = render(<ChatFeed chat={msgs} decisions={dec2} questions={qs} focusId={null} onOpenFlag={onOpenFlag} />);
    expect(container.querySelectorAll(".msg-group").length).toBe(4);
    expect(container.querySelectorAll(".msg.fired").length).toBe(2); expect(container.querySelectorAll(".flag.skipped").length).toBe(1); expect(container.querySelectorAll(".flag.pending").length).toBe(1);
    expect(container.textContent).toContain("big q 70%"); expect(container.textContent).toContain("Level 1.3"); expect(container.textContent).toContain("follows");
    fireEvent.click(container.querySelector(".flag.open")!); expect(onOpenFlag).toHaveBeenCalledWith("c1");
    // c1 and c2 are both Alice's within 90 s: one group.
    fireEvent.click(screen.getByText("flagged")); expect(container.querySelectorAll(".msg-group").length).toBe(1); expect(container.querySelectorAll(".msg").length).toBe(2);
    fireEvent.click(screen.getByText("questions")); expect(container.querySelectorAll(".msg-group").length).toBe(1);
    fireEvent.click(screen.getByText("all"));
    fireEvent.change(screen.getByLabelText("filter chat"), { target: { value: "BOB" } }); expect(container.querySelectorAll(".msg-group").length).toBe(1);
    fireEvent.change(screen.getByLabelText("filter chat"), { target: { value: "zzz" } }); expect(screen.getByText("No message matches.")).toBeTruthy();
    fireEvent.change(screen.getByLabelText("filter chat"), { target: { value: "" } });
    fireEvent.click(screen.getAllByTitle("viewer details")[0]);
    expect(container.querySelector(".user-card")?.textContent).toContain("3 messages in buffer · 2 flagged");
    fireEvent.click(screen.getByText("🔔 mute this viewer's alerts here"));
    expect(JSON.parse(localStorage.getItem("jev.mutedUsers")!)).toEqual(["u1"]); expect(container.querySelectorAll(".msg-group.muted-user").length).toBe(2);
    fireEvent.click(screen.getByText("🔕 alerts muted in this console"));
    expect(JSON.parse(localStorage.getItem("jev.mutedUsers")!)).toEqual([]);
    fireEvent.click(container.querySelector('.user-card [aria-label="close"]')!); expect(container.querySelector(".user-card")).toBeNull();
    fireEvent.click(screen.getAllByTitle("viewer details")[1]);
    expect(container.querySelector(".user-card")?.textContent).toContain("2 messages in buffer · 0 flagged");
    const log = container.querySelector(".chat")!;
    scrollBox(log, 0);
    rerender(<ChatFeed chat={[...msgs, chat({ id: "c6", ts: now, text: "new one" })]} decisions={decisions} questions={qs} focusId={null} onOpenFlag={onOpenFlag} />);
    expect(screen.getByText("1 new ↓")).toBeTruthy();
    fireEvent.click(screen.getByText("1 new ↓")); expect(screen.queryByText(/new ↓/)).toBeNull();
    scrollBox(log, 0); expect(screen.getByText("newest ↓")).toBeTruthy(); scrollBox(log, 900);
    const scrollInto = spyOn(Element.prototype, "scrollIntoView").mockImplementation(() => {});
    rerender(<ChatFeed chat={msgs} decisions={decisions} questions={qs} focusId="c3" onOpenFlag={onOpenFlag} />);
    expect(scrollInto).toHaveBeenCalled(); expect(container.querySelector('[data-id="c3"]')?.classList.contains("flash")).toBe(true);
    await waitFor(() => expect(container.querySelector('[data-id="c3"]')?.classList.contains("flash")).toBe(false), { timeout: 3000 });
    rerender(<ChatFeed chat={msgs} decisions={decisions} questions={qs} focusId="missing" onOpenFlag={onOpenFlag} />);
    rerender(<ChatFeed chat={[]} decisions={{}} questions={[]} focusId={null} onOpenFlag={onOpenFlag} />);
    expect(screen.getByText("No chat yet.")).toBeTruthy();
    scrollInto.mockRestore();
  });
});

describe("Flagged", () => {
  test("filters, chips, search, card bodies and actions", async () => {
    const patch = spyOn(api, "patchHighlight").mockResolvedValue({ ok: true } as any);
    const remove = spyOn(api, "removeHighlight").mockResolvedValue({ ok: true, undoMs: 60_000 } as any);
    const restore = spyOn(api, "restoreHighlight").mockResolvedValue({ ok: true } as any);
    const clear = spyOn(api, "clearHighlights").mockResolvedValue({ ok: true, removed: ["h3"], undoMs: 60_000 } as any);
    const feedback = spyOn(api, "feedback").mockResolvedValue({ ok: true, rewritten: false } as any);
    const write = mock(async () => {}); Object.defineProperty(navigator, "clipboard", { value: { writeText: write }, configurable: true });
    const scrollInto = spyOn(Element.prototype, "scrollIntoView").mockImplementation(() => {});
    const onJump = mock(() => {}), onWatch = mock(() => {});
    const hls = [highlight(), transcriptHl(), sceneHl({ resolved: true }), roomHl({ pinned: true, evidence: undefined, version: undefined })];
    const qs = [question(), messageQ()];
    const { container, rerender } = render(<><Flagged highlights={hls} questions={qs} focusId="h2" onJump={onJump} onWatch={onWatch} canWatch /><DialogHost /></>);
    expect(container.querySelectorAll(".hl").length).toBe(3); expect(scrollInto).toHaveBeenCalled(); expect(container.querySelector(".hl.focused")).not.toBeNull();
    expect(container.textContent).toContain("Politics again."); expect(container.textContent).toContain("bob wow"); expect(container.textContent).toContain("120 viewers (rising)");
    fireEvent.click(screen.getByText("pinned")); expect(container.querySelectorAll(".hl").length).toBe(1);
    fireEvent.click(screen.getByText("resolved")); expect(container.querySelectorAll(".hl").length).toBe(1); expect(container.textContent).toContain("An empty chair.");
    fireEvent.click(screen.getByText("all")); expect(container.querySelectorAll(".hl").length).toBe(4);
    fireEvent.click(screen.getByRole("button", { name: "💬 message" })); expect(container.querySelectorAll(".hl").length).toBe(1);
    fireEvent.click(screen.getByRole("button", { name: "💬 message" }));
    // Only the transcript card carries the "Host topic" flag.
    fireEvent.click(screen.getByRole("button", { name: "Host topic" }));
    expect(container.querySelectorAll(".hl").length).toBe(1);
    fireEvent.change(screen.getByLabelText("search flagged"), { target: { value: "election" } });
    expect(container.querySelectorAll(".hl").length).toBe(1);
    fireEvent.change(screen.getByLabelText("search flagged"), { target: { value: "nothing-matches" } });
    expect(screen.getByText("No flagged item matches these filters.")).toBeTruthy();
    fireEvent.change(screen.getByLabelText("search flagged"), { target: { value: "" } });
    fireEvent.click(screen.getByRole("button", { name: "Host topic" }));
    expect(container.querySelectorAll(".hl").length).toBe(4);
    fireEvent.click(screen.getByText("open"));
    const card = container.querySelector(".hl.message")!;
    fireEvent.click(card.querySelector('[aria-label="pin"]')!); expect(patch).toHaveBeenCalledWith("h1", { pinned: true });
    fireEvent.click(card.querySelector('[aria-label="mark handled"]')!); expect(patch).toHaveBeenCalledWith("h1", { resolved: true });
    fireEvent.click(card.querySelector('[aria-label="watch this moment"]')!); expect(onWatch).toHaveBeenCalledWith(T0 + 2000);
    fireEvent.click(card.querySelector('[aria-label="show in chat"]')!); expect(onJump).toHaveBeenCalledWith("c1");
    fireEvent.click(card.querySelector('[aria-label="copy text"]')!); expect(write).toHaveBeenCalledWith("Alice: Hello host, what time is it?");
    fireEvent.click(card.querySelector('[aria-label="why did this fire"]')!); expect(card.querySelector(".hl-evidence")).not.toBeNull();
    fireEvent.click(card.querySelector('[aria-label="rate this flag"]')!);
    const dlg = container.querySelector("dialog")!;
    await waitFor(() => expect(dlg.open).toBe(true));
    fireEvent.click(screen.getByText("Cancel"));
    fireEvent.click(card.querySelector('[aria-label="rate this flag"]')!);
    await waitFor(() => expect(dlg.open).toBe(true));
    fireEvent.change(dlg.querySelector("select")!, { target: { value: "correct:m1" } });
    fireEvent.click(screen.getByText("Send"));
    await waitFor(() => expect(feedback).toHaveBeenCalled());
    expect(feedback.mock.calls[0][0]).toMatchObject({ verdict: "correct", questionId: "m1", highlightId: "h1" });
    await waitFor(() => expect(getState().toasts.some((t) => t.title === "Feedback recorded")).toBe(true));
    // A flag whose question is unknown: nothing is sent.
    rerender(<><Flagged highlights={hls} questions={[question()]} focusId={null} onJump={onJump} onWatch={onWatch} canWatch={false} /><DialogHost /></>);
    fireEvent.click(screen.getByText("all"));
    fireEvent.click(container.querySelector('.hl.message [aria-label="rate this flag"]')!);
    await waitFor(() => expect(dlg.open).toBe(true));
    fireEvent.click(screen.getByText("Send"));
    await waitFor(() => expect(dlg.open).toBe(false));
    expect(feedback).toHaveBeenCalledTimes(1);
    expect(container.querySelector('[aria-label="watch this moment"]')).toBeNull();
    // Copy of a transcript and of a scene card; evidence-less card has no "why".
    fireEvent.click(container.querySelector('.hl.transcript [aria-label="copy text"]')!); expect(write).toHaveBeenLastCalledWith("Let us talk about the election. Politics again.");
    fireEvent.click(container.querySelector('.hl.scene [aria-label="copy text"]')!); expect(write).toHaveBeenLastCalledWith("An empty chair.");
    fireEvent.click(container.querySelector('.hl.room [aria-label="copy text"]')!); expect(write).toHaveBeenLastCalledWith("");
    expect(container.querySelector('.hl.room [aria-label="why did this fire"]')).toBeNull();
    fireEvent.click(container.querySelector('.hl.scene [aria-label="reopen"]')!); expect(patch).toHaveBeenCalledWith("h3", { resolved: false });
    fireEvent.click(container.querySelector('.hl.room [aria-label="unpin"]')!); expect(patch).toHaveBeenCalledWith("h4", { pinned: false });
    // Delete with undo, clear handled with undo.
    fireEvent.click(container.querySelector('.hl.message [aria-label="delete"]')!);
    await waitFor(() => expect(remove).toHaveBeenCalledWith("h1"));
    await waitFor(() => expect(getState().toasts.some((t) => t.title === "Flag deleted")).toBe(true));
    act(() => getState().toasts.find((t) => t.title === "Flag deleted")!.action!.run());
    expect(restore).toHaveBeenCalledWith("h1");
    fireEvent.click(screen.getByText("clear handled"));
    await waitFor(() => expect(dlg.open).toBe(true));
    fireEvent.click(screen.getByText("Cancel"));
    fireEvent.click(screen.getByText("clear handled"));
    await waitFor(() => expect(dlg.open).toBe(true));
    fireEvent.click(screen.getByText("Clear"));
    await waitFor(() => expect(clear).toHaveBeenCalledWith("resolved"));
    await waitFor(() => expect(getState().toasts.some((t) => t.title === "1 flags cleared")).toBe(true));
    act(() => getState().toasts.find((t) => t.title === "1 flags cleared")!.action!.run());
    expect(restore).toHaveBeenCalledWith("h3");
    clear.mockRejectedValue(new Error("x"));
    fireEvent.click(screen.getByText("clear handled"));
    await waitFor(() => expect(dlg.open).toBe(true));
    fireEvent.click(screen.getByText("Clear"));
    await waitFor(() => expect(clear).toHaveBeenCalledTimes(2));
    // Every failure path is swallowed: delete, pin / resolve patches, both undo restores.
    remove.mockRejectedValue(new Error("x"));
    await removeWithUndo(highlight());
    patch.mockRejectedValue(new Error("x"));
    fireEvent.click(container.querySelector('.hl.transcript [aria-label="pin"]')!);
    fireEvent.click(container.querySelector('.hl.transcript [aria-label="mark handled"]')!);
    restore.mockRejectedValue(new Error("x"));
    act(() => { for (const t of getState().toasts) t.action?.run(); });
    await new Promise((r) => setTimeout(r, 20));
    feedback.mockRejectedValue(new Error("x"));
    fireEvent.click(container.querySelector('.hl.transcript [aria-label="rate this flag"]')!);
    await waitFor(() => expect(dlg.open).toBe(true));
    fireEvent.click(screen.getByText("Send"));
    await waitFor(() => expect(feedback).toHaveBeenCalledTimes(2));
    // A card without stored evidence sends what it shows (transcript text) as the state excerpt.
    feedback.mockResolvedValue({ ok: true, rewritten: false } as any);
    rerender(<><Flagged highlights={[transcriptHl({ id: "h5", evidence: undefined })]} questions={[question()]} focusId={null} onJump={onJump} onWatch={onWatch} canWatch={false} /><DialogHost /></>);
    fireEvent.click(container.querySelector('.hl.transcript [aria-label="rate this flag"]')!);
    await waitFor(() => expect(dlg.open).toBe(true));
    fireEvent.click(screen.getByText("Send"));
    await waitFor(() => expect(feedback).toHaveBeenCalledTimes(3));
    expect(feedback.mock.calls[2][0]).toMatchObject({ stateExcerpt: { transcript: "Let us talk about the election. Politics again." } });
    render(<Flagged highlights={[]} questions={[]} focusId={null} onJump={onJump} onWatch={onWatch} canWatch />);
    expect(screen.getByText(/Nothing flagged yet/)).toBeTruthy();
    patch.mockRestore(); remove.mockRestore(); restore.mockRestore(); clear.mockRestore(); feedback.mockRestore(); scrollInto.mockRestore();
  });
});
